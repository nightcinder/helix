/** Deployment values: environment variable first, then a Gradle property (-PNAME=... or ~/.gradle/gradle.properties). */
fun siteValue(name: String): String =
    (System.getenv(name)?.takeIf { it.isNotBlank() } ?: findProperty(name)?.toString()).orEmpty().trim()

