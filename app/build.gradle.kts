// GameStream pairing/serverinfo is plain HTTP on 47989, so the stream host needs a cleartext exception.
// With HELIX_STREAM_HOST set, only that address gets it; without it the host is entered at runtime and can be
// any LAN address, so cleartext is allowed app-wide (all Helix's own server traffic is https/wss regardless).
val generateNetworkSecurityConfig by tasks.registering {
    val streamHost = siteValue("HELIX_STREAM_HOST")
    val outDir = layout.buildDirectory.dir("generated/helixSite/res")
    inputs.property("streamHost", streamHost)
    outputs.dir(outDir)
    doLast {
        val xml = outDir.get().file("xml/network_security_config.xml").asFile
        xml.parentFile.mkdirs()
        val body = if (streamHost.isNotEmpty()) {
            """
            |    <base-config cleartextTrafficPermitted="false" />
            |    <domain-config cleartextTrafficPermitted="true">
            |        <domain includeSubdomains="false">$streamHost</domain>
            |    </domain-config>
            """.trimMargin()
        } else {
            """    <base-config cleartextTrafficPermitted="true" />"""
        }
        xml.writeText(
            "<?xml version=\"1.0\" encoding=\"utf-8\"?>\n" +
                "<!-- Generated by app/build.gradle.kts (generateNetworkSecurityConfig); do not edit. -->\n" +
                "<network-security-config>\n$body\n</network-security-config>\n",
        )
    }
}

